-- ====================================================================
-- 1. PROFILES & STORE SETTINGS
-- ====================================================================

CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    email TEXT NOT NULL,
    full_name TEXT,
    role TEXT NOT NULL DEFAULT 'cashier' CHECK (role IN ('owner', 'admin', 'cashier')),
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.store_settings (
    id TEXT PRIMARY KEY DEFAULT 'main',
    store_name TEXT NOT NULL DEFAULT 'AuraPOS Bistro & Grill',
    address TEXT DEFAULT '124 Market Street, San Francisco, CA',
    phone TEXT DEFAULT '+1 (555) 019-2831',
    email TEXT DEFAULT 'contact@aurapos.example.com',
    currency TEXT NOT NULL DEFAULT 'USD',
    currency_symbol TEXT NOT NULL DEFAULT '$',
    tax_rate NUMERIC(5, 2) NOT NULL DEFAULT 8.25,
    receipt_header TEXT DEFAULT 'Thank you for dining with us!',
    receipt_footer TEXT DEFAULT 'Please come again!',
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- ====================================================================
-- 2. CATEGORIES, PRODUCTS & ITEMS
-- ====================================================================

CREATE TABLE IF NOT EXISTS public.categories (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name TEXT NOT NULL UNIQUE,
    color_hex TEXT DEFAULT '#0288D1',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name TEXT NOT NULL,
    price NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    category TEXT DEFAULT 'General',
    stock_level INTEGER NOT NULL DEFAULT 0,
    image_url TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.items (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name TEXT NOT NULL,
    category_id BIGINT REFERENCES public.categories(id) ON DELETE SET NULL,
    category_name TEXT DEFAULT 'General',
    price NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    cost NUMERIC(10, 2) DEFAULT 0.00,
    sku TEXT,
    barcode TEXT,
    sold_by TEXT DEFAULT 'EACH' CHECK (sold_by IN ('EACH', 'WEIGHT')),
    in_stock NUMERIC(10, 2) DEFAULT 0.0,
    low_stock_threshold NUMERIC(10, 2) DEFAULT 5.0,
    track_stock BOOLEAN DEFAULT TRUE,
    color_hex TEXT DEFAULT '#0288D1',
    modifier_ids TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.modifier_groups (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name TEXT NOT NULL,
    options_json TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.modifiers (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name TEXT NOT NULL,
    price NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    category_id BIGINT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ====================================================================
-- 3. CUSTOMERS & LOYALTY
-- ====================================================================

CREATE TABLE IF NOT EXISTS public.customers (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    name TEXT NOT NULL,
    phone TEXT,
    email TEXT,
    customer_code TEXT UNIQUE,
    points_balance NUMERIC(10, 2) DEFAULT 0.00,
    total_visits INTEGER DEFAULT 0,
    total_spent NUMERIC(10, 2) DEFAULT 0.00,
    note TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.loyalty_points (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    customer_id BIGINT NOT NULL REFERENCES public.customers(id) ON DELETE CASCADE,
    points NUMERIC(10, 2) NOT NULL,
    description TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ====================================================================
-- 4. SHIFTS, CASH ACTIONS & TIMECARDS
-- ====================================================================

CREATE TABLE IF NOT EXISTS public.shifts (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    opened_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    closed_at TIMESTAMPTZ,
    cashier_name TEXT NOT NULL,
    starting_cash NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    cash_payments NUMERIC(10, 2) DEFAULT 0.00,
    cash_refunds NUMERIC(10, 2) DEFAULT 0.00,
    cash_paid_in NUMERIC(10, 2) DEFAULT 0.00,
    cash_paid_out NUMERIC(10, 2) DEFAULT 0.00,
    card_payments NUMERIC(10, 2) DEFAULT 0.00,
    actual_cash_counted NUMERIC(10, 2),
    is_open BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.cash_actions (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    shift_id BIGINT NOT NULL REFERENCES public.shifts(id) ON DELETE CASCADE,
    is_pay_in BOOLEAN NOT NULL,
    amount NUMERIC(10, 2) NOT NULL,
    comment TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.timecards (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    employee_name TEXT NOT NULL,
    clock_in_time TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    clock_out_time TIMESTAMPTZ,
    total_hours NUMERIC(10, 2) DEFAULT 0.00,
    is_clocked_in BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ====================================================================
-- 5. RECEIPTS & TRANSACTIONS
-- ====================================================================

CREATE TABLE IF NOT EXISTS public.receipts (
    id TEXT PRIMARY KEY,
    receipt_number TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    shift_id BIGINT,
    cashier_name TEXT NOT NULL DEFAULT 'Cashier',
    ticket_name TEXT,
    dining_option TEXT DEFAULT 'Dine in',
    subtotal NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    tax_amount NUMERIC(10, 2) DEFAULT 0.00,
    discount_amount NUMERIC(10, 2) DEFAULT 0.00,
    tip_amount NUMERIC(10, 2) DEFAULT 0.00,
    total_amount NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    payment_type TEXT NOT NULL DEFAULT 'CASH',
    payment_details_json TEXT,
    customer_id BIGINT REFERENCES public.customers(id) ON DELETE SET NULL,
    customer_name TEXT,
    is_refunded BOOLEAN DEFAULT FALSE,
    refund_timestamp TIMESTAMPTZ,
    items_summary_json TEXT,
    idempotency_key TEXT UNIQUE
);

CREATE TABLE IF NOT EXISTS public.receipt_items (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    receipt_id TEXT NOT NULL REFERENCES public.receipts(id) ON DELETE CASCADE,
    item_id BIGINT,
    item_name TEXT NOT NULL,
    unit_price NUMERIC(10, 2) NOT NULL,
    quantity NUMERIC(10, 2) NOT NULL DEFAULT 1.0,
    selected_modifiers_json TEXT DEFAULT '',
    modifiers_cost NUMERIC(10, 2) DEFAULT 0.00,
    comment TEXT,
    discount_percent NUMERIC(10, 2) DEFAULT 0.00,
    line_total NUMERIC(10, 2) NOT NULL
);

